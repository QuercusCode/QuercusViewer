const CODE_TO_LANG: Record<string, string> = {
    en: 'English (US)',
    es: 'Spanish (ES)',
    fr: 'French (FR)',
    de: 'German (DE)',
    pt: 'Portuguese (PT)',
    hi: 'Hindi (HI)',
    zh: 'Chinese (ZH)',
};

export function useTranslation() {
    const [, forceUpdate] = useState(0);

    // Re-render whenever i18next language changes (keeps viewer in sync with landing page switcher)
    useEffect(() => {
        const handler = () => forceUpdate(n => n + 1);
        i18next.on('languageChanged', handler);
        return () => { i18next.off('languageChanged', handler); };
    }, []);

    const code = (i18next.language || 'en').slice(0, 2);
    const langKey = CODE_TO_LANG[code] || 'English (US)';
    const t = translations[langKey as keyof typeof translations] || translations['English (US)'];

    // Proxy falls back to English for any missing key
    const safeT = new Proxy(t, {
        get(target, prop: string) {
            return target[prop as keyof typeof target] || translations['English (US)'][prop as keyof typeof translations['English (US)']] || prop;
        }
    });

    return { t: safeT, lang: langKey };
}
