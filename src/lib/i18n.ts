export function useTranslation() {
    const { user } = useAuth();
    const lang = user?.user_metadata?.language || 'English (US)';
    const t = translations[lang as keyof typeof translations] || translations['English (US)'];
    
    // Add a fast fallback for any unmapped keys so the app doesn't crash:
    const safeT = new Proxy(t, {
        get(target, prop: string) {
            return target[prop as keyof typeof target] || translations['English (US)'][prop as keyof typeof translations['English (US)']] || prop;
        }
    });

    return { t: safeT, lang };
}
